double fmod(double x, double y)
{
        return x - (double)((long long)(x / y)) * y;
}
/* ------------------------------------------------------------------------------------------------- */

/* ------------------------------------------------------------------------------------------------- */
double pow(double base, double e)
{
        if (base == 0)
                return e == 0 ? 1 : 0;
        return exp(e * log(base));
}
